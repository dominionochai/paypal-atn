// A trace is the contract between the ATN engine and the demo UI in ui/. Schema: "atn-trace/1".
import fs from 'node:fs';
import path from 'node:path';

export const SCHEMA = 'atn-trace/1';

/** Order shown in the UI and played by the "Story" button (the first three, in this order). */
export const SCENARIO_ORDER = ['prompt-injection', 'happy-path', 'bad-model', 'revoked-mid-stream', 'trust-gate'];
export const STORY = ['prompt-injection', 'happy-path', 'bad-model'];

