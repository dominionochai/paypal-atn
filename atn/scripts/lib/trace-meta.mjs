/** Writes ui/traces/<scenario>.json plus ui/traces/bundle.js (a classic script, so the UI also works from file://). */
export function writeTraces(dir, traces) {
  fs.mkdirSync(dir, { recursive: true });
  const byName = {};
  for (const trace of traces) {
    byName[trace.scenario] = trace;
    fs.writeFileSync(path.join(dir, trace.scenario + '.json'), JSON.stringify(trace, null, 2) + '\n');
  }
  const order = SCENARIO_ORDER.filter((name) => byName[name] !== undefined);
  const banner = '// Generated by scripts/make-sample-traces.mjs or scripts/export-traces.mjs. Do not edit by hand.\n';
  const body = '(function () {\n  window.ATN_TRACES = ' + JSON.stringify(byName) + ';\n  window.ATN_TRACE_ORDER = ' + JSON.stringify(order) + ';\n  window.ATN_STORY = ' + JSON.stringify(STORY) + ';\n})();\n';
  fs.writeFileSync(path.join(dir, 'bundle.js'), banner + body);
}
